"""The book's structure: parts and chapters. Every tool and test reads it from here.

    part1-foundations/ch01-diagnostic/
        README.md       chapter text
        notebook.py     lab source (percent format) - edit this
        notebook.ipynb  lab, generated by tools/nbbuild.py
        solutions.md    worked answers to exercises and checkpoint questions
        solutions.py    reference code for the graded exercises (graded in CI)

Graders live in ``src/grading/chNN.py``; the lab imports ``grading.chNN``.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

PARTS = [
    ("part1-foundations", "Part I · Foundations of ML Engineering", "requirements.txt"),
    ("part2-ml-at-scale", "Part II · Machine Learning at Scale", "requirements-part2.txt"),
    ("part3-deep-learning-systems", "Part III · Deep Learning and Large-Scale Systems", "requirements-part3.txt"),
]
CAPSTONES_DIR = REPO_ROOT / "part4-capstones"


@dataclass(frozen=True)
class Chapter:
    number: int
    part: str
    folder: Path

    @property
    def source(self) -> Path:
        return self.folder / "notebook.py"

    @property
    def notebook(self) -> Path:
        return self.folder / "notebook.ipynb"

    @property
    def solutions_md(self) -> Path:
        return self.folder / "solutions.md"

    @property
    def solutions_py(self) -> Path:
        return self.folder / "solutions.py"

    @property
    def grader_module(self) -> str:
        return f"grading.ch{self.number:02d}"

    @property
    def title(self) -> str:
        for line in self.source.read_text(encoding="utf-8").splitlines():
            m = re.match(r"^# # Chapter \d+ · (.+)$", line)
            if m:
                return m.group(1).strip()
        return self.folder.name

    @property
    def rel(self) -> str:
        return self.folder.relative_to(REPO_ROOT).as_posix()


def chapters(part: str | None = None) -> list[Chapter]:
    out = []
    for part_dir, _, _ in PARTS:
        if part and part != part_dir:
            continue
        for folder in sorted((REPO_ROOT / part_dir).glob("ch[0-9][0-9]-*")):
            if (folder / "notebook.py").exists():
                out.append(Chapter(int(folder.name[2:4]), part_dir, folder))
    return sorted(out, key=lambda c: c.number)


def capstone_notebooks() -> list[Path]:
    return sorted(CAPSTONES_DIR.glob("cap*/walkthrough.py"))


def all_sources() -> list[Path]:
    """Every percent-format lab source: chapters, then capstone walkthroughs."""
    return [c.source for c in chapters()] + capstone_notebooks()


def all_notebooks() -> list[Path]:
    return [p.with_suffix(".ipynb") for p in all_sources()]
