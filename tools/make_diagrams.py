#!/usr/bin/env python3
"""Generate every course diagram as self-contained SVG, plus an index page.

    python tools/make_diagrams.py          # write figures/*.svg and appendices/figures.md
    python tools/make_diagrams.py --check  # fail if anything is stale (CI)

Conventions (read before adding a figure):

* Draw with :mod:`svgkit` (``Canvas``) and register with ``@diagram``. The
  function returns ``(filename, svg, caption)``.
* One module per area, so authors never edit the same file:
  ``diagrams_l1.py`` (Level 1), ``diagrams_l2a.py`` / ``l2b`` (Level 2 notebooks
  01-10 / 11-20), ``diagrams_l3a.py`` / ``l3b`` (Level 3), ``diagrams_docs.py``
  (handbook and guides).
* File names are prefixed by part: ``l1-`` (Part I), ``l2-`` (Part II),
  ``l3-`` (Part III); ``hb-`` for background figures. (The six original Level 1 names are kept as they are.)
* Clean, not busy: at most ~8 boxes, one idea per figure, short labels, one
  takeaway box. ``Canvas.box`` raises ``OverflowError`` if text does not fit.
* Every figure must be *used*: embedded in a chapter (README with a relative
  path, notebook with a raw GitHub URL). appendices/figures.md lists them all.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import diagrams_docs  # noqa: E402,F401
import diagrams_l1  # noqa: E402,F401
import diagrams_l2a  # noqa: E402,F401
import diagrams_l2b  # noqa: E402,F401
import diagrams_l3a  # noqa: E402,F401
import diagrams_l3b  # noqa: E402,F401
from svgkit import DIAGRAMS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "figures"
INDEX = ROOT / "appendices" / "figures.md"

GROUPS = [("l1-", "Part I"), ("l2-", "Part II"), ("l3-", "Part III"), ("hb-", "Background figures")]


def build() -> dict[str, str]:
    files: dict[str, str] = {}
    captions: dict[str, str] = {}
    for fn in DIAGRAMS:
        name, svg, caption = fn()
        if name in files:
            raise ValueError(f"two diagrams are both named {name}")
        files[name] = svg
        captions[name] = caption
    files["__index__"] = index_page(captions)
    return files


def index_page(captions: dict[str, str]) -> str:
    lines = ["# Appendix · List of figures", "",
             "Every figure in the course, generated by `tools/make_diagrams.py`. "
             "Click a title to open the full-size SVG.", ""]
    def group_of(name):
        for prefix, title in GROUPS:
            if name.startswith(prefix):
                return title
        return "Part I"
    order = [t for _, t in GROUPS]
    for title in order:
        names = sorted(n for n in captions if group_of(n) == title)
        if not names:
            continue
        lines += [f"## {title}", "", "| Figure | What it shows |", "|---|---|"]
        lines += [f"| [{n}](../figures/{n}) | {captions[n]} |" for n in names]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = build()
    OUT.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, text in files.items():
        path = INDEX if name == "__index__" else OUT / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8")
    if not args.check:
        print(f"wrote {len(files) - 1} diagrams and {INDEX.relative_to(ROOT)}")
        return 0
    orphans = sorted(p.name for p in OUT.glob("*.svg") if p.name not in files)
    if stale or orphans:
        print("stale: " + ", ".join(stale) + ("; orphan svg files: " + ", ".join(orphans) if orphans else ""),
              file=sys.stderr)
        print("run: python tools/make_diagrams.py", file=sys.stderr)
        return 1
    print(f"all {len(files) - 1} diagrams and the index are up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
